function createPage(blueprint: BusinessAppBlueprint) {
  const blueprintJson = JSON.stringify(blueprint, null, 2);

  return `"use client";

import { type ChangeEvent, type FormEvent, useMemo, useState } from "react";

type FieldKind = "text" | "number" | "select" | "textarea";

type BusinessField = {
  key: string;
  label: string;
  kind: FieldKind;
  placeholder?: string;
  options?: string[];
};

type BusinessRecord = {
  id: string;
  status: string;
  data: Record<string, string>;
};

type BusinessAppBlueprint = {
  appType: string;
  appName: string;
  slug: string;
  eyebrow: string;
  title: string;
  description: string;
  primaryEntity: string;
  createTitle: string;
  actionLabel: string;
  searchPlaceholder: string;
  fields: BusinessField[];
  statuses: string[];
  closedStatuses: string[];
  titleFieldKey: string;
  contactFieldKey: string;
  valueFieldKey: string;
  followUpFieldKey: string;
  notesFieldKey: string;
  subtitleFieldKeys: string[];
  statsLabels: {
    active: string;
    value: string;
    followUp: string;
    closed: string;
  };
  samples: BusinessRecord[];
  nextSteps: string[];
};

const blueprint: BusinessAppBlueprint = ${blueprintJson};

const money = new Intl.NumberFormat("en-US", {
  style: "currency",
  currency: "USD",
  maximumFractionDigits: 0,
});

function getStatusClass(status: string) {
  return "status-badge " + status.toLowerCase().replace(/\\\\s+/g, "-");
}

function createEmptyForm() {
  return blueprint.fields.reduce<Record<string, string>>((result, field) => {
    result[field.key] = field.options?.[0] || "";
    return result;
  }, {});
}

function getRecordValue(record: BusinessRecord) {
  return Number(record.data[blueprint.valueFieldKey]) || 0;
}

function getRecordTitle(record: BusinessRecord) {
  return record.data[blueprint.titleFieldKey] || blueprint.primaryEntity;
}

function getRecordSubtitle(record: BusinessRecord) {
  return blueprint.subtitleFieldKeys
    .map((key) => record.data[key])
    .filter(Boolean)
    .join(" · ");
}

export default function Page() {
  const [records, setRecords] = useState<BusinessRecord[]>(blueprint.samples);
  const [search, setSearch] = useState("");
  const [form, setForm] = useState<Record<string, string>>(createEmptyForm());

  const stats = useMemo(() => {
    const activeRecords = records.filter(
      (record) => !blueprint.closedStatuses.includes(record.status),
    );

    const closedRecords = records.filter((record) =>
      blueprint.closedStatuses.includes(record.status),
    );

    const totalValue = activeRecords.reduce(
      (total, record) => total + getRecordValue(record),
      0,
    );

    const followUps = activeRecords.filter((record) => {
      const value = record.data[blueprint.followUpFieldKey];
      return value && value.toLowerCase() !== "not scheduled";
    });

    return [
      {
        label: blueprint.statsLabels.active,
        value: activeRecords.length,
        helper: "Currently moving",
      },
      {
        label: blueprint.statsLabels.value,
        value: money.format(totalValue),
        helper: "Open estimated value",
      },
      {
        label: blueprint.statsLabels.followUp,
        value: followUps.length,
        helper: "Needs next action",
      },
      {
        label: blueprint.statsLabels.closed,
        value: closedRecords.length,
        helper: "Completed or closed",
      },
    ];
  }, [records]);

  const filteredRecords = useMemo(() => {
    const query = search.trim().toLowerCase();

    if (!query) return records;

    return records.filter((record) =>
      [
        record.status,
        ...Object.values(record.data),
      ]
        .join(" ")
        .toLowerCase()
        .includes(query),
    );
  }, [records, search]);

  function handleChange(
    event: ChangeEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>,
  ) {
    const { name, value } = event.target;

    setForm((current) => ({
      ...current,
      [name]: value,
    }));
  }

  function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();

    const titleValue = form[blueprint.titleFieldKey]?.trim();

    if (!titleValue) return;

    const newRecord: BusinessRecord = {
      id: "record-" + Date.now(),
      status: blueprint.statuses[0] || "New",
      data: { ...form },
    };

    setRecords((current) => [newRecord, ...current]);
    setForm(createEmptyForm());
  }

  function moveStatus(id: string) {
    setRecords((current) =>
      current.map((record) => {
        if (record.id !== id) return record;

        const currentIndex = blueprint.statuses.indexOf(record.status);
        const nextStatus =
          blueprint.statuses[(currentIndex + 1) % blueprint.statuses.length] ||
          blueprint.statuses[0] ||
          record.status;

        return {
          ...record,
          status: nextStatus,
        };
      }),
    );
  }

  function renderField(field: BusinessField) {
    if (field.kind === "textarea") {
      return (
        <textarea
          id={field.key}
          name={field.key}
          value={form[field.key] || ""}
          onChange={handleChange}
          placeholder={field.placeholder || field.label}
          rows={4}
        />
      );
    }

    if (field.kind === "select") {
      return (
        <select
          id={field.key}
          name={field.key}
          value={form[field.key] || field.options?.[0] || ""}
          onChange={handleChange}
        >
          {(field.options || []).map((option) => (
            <option key={option}>{option}</option>
          ))}
        </select>
      );
    }

    return (
      <input
        id={field.key}
        name={field.key}
        value={form[field.key] || ""}
        onChange={handleChange}
        type={field.kind === "number" ? "number" : "text"}
        min={field.kind === "number" ? "0" : undefined}
        placeholder={field.placeholder || field.label}
        required={field.key === blueprint.titleFieldKey}
      />
    );
  }

  return (
    <main className="page-shell">
      <section className="hero-card">
        <div>
          <p className="eyebrow">{blueprint.eyebrow}</p>
          <h1>{blueprint.title}</h1>
          <p className="hero-copy">{blueprint.description}</p>
        </div>
      </section>

      <section className="stat-grid" aria-label="Business overview">
        {stats.map((stat) => (
          <article className="stat-card" key={stat.label}>
            <span>{stat.label}</span>
            <strong>{stat.value}</strong>
            <p>{stat.helper}</p>
          </article>
        ))}
      </section>

      <section className="dashboard-grid">
        <article className="panel">
          <div className="panel-heading">
            <p className="eyebrow">Create</p>
            <h2>{blueprint.createTitle}</h2>
          </div>

          <form className="stacked-form" onSubmit={handleSubmit}>
            {blueprint.fields.map((field) => (
              <div className="form-row" key={field.key}>
                <label htmlFor={field.key}>{field.label}</label>
                {renderField(field)}
              </div>
            ))}

            <button className="button primary full-width" type="submit">
              {blueprint.actionLabel}
            </button>
          </form>
        </article>

        <article className="panel">
          <div className="panel-heading split">
            <div>
              <p className="eyebrow">Workspace</p>
              <h2>{blueprint.primaryEntity}</h2>
            </div>

            <label className="search-label" htmlFor="search">
              <span className="sr-only">Search</span>
              <input
                id="search"
                type="search"
                value={search}
                onChange={(event) => setSearch(event.target.value)}
                placeholder={blueprint.searchPlaceholder}
              />
            </label>
          </div>

          <div className="record-list">
            {filteredRecords.map((record) => (
              <div className="record-card" key={record.id}>
                <div className="record-topline">
                  <div>
                    <h3>{getRecordTitle(record)}</h3>
                    <p>{getRecordSubtitle(record)}</p>
                  </div>

                  <span className={getStatusClass(record.status)}>
                    {record.status}
                  </span>
                </div>

                <p className="record-note">
                  {record.data[blueprint.notesFieldKey] || "No notes yet."}
                </p>

                <div className="record-meta">
                  <span>{record.data[blueprint.contactFieldKey] || "No contact"}</span>
                  <span>{money.format(getRecordValue(record))}</span>
                  <span>
                    Follow-up: {record.data[blueprint.followUpFieldKey] || "Not scheduled"}
                  </span>
                  <button
                    className="table-action"
                    type="button"
                    onClick={() => moveStatus(record.id)}
                  >
                    Move status
                  </button>
                </div>
              </div>
            ))}
          </div>
        </article>
      </section>
    </main>
  );
}
`;
}

