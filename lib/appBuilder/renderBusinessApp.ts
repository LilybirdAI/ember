function createPreviewHtml(blueprint: BusinessAppBlueprint) {
  const active = blueprint.samples.filter(
    (item) => !blueprint.closedStatuses.includes(item.status),
  ).length;

  const totalValue = blueprint.samples.reduce((sum, item) => {
    return sum + (Number(item.data[blueprint.valueFieldKey]) || 0);
  }, 0);

  const sampleCards = blueprint.samples
    .slice(0, 3)
    .map((item) => {
      const title = item.data[blueprint.titleFieldKey] || blueprint.primaryEntity;
      const subtitle = blueprint.subtitleFieldKeys
        .map((key) => item.data[key])
        .filter(Boolean)
        .join(" · ");

      return `<div class="card"><strong>${title}</strong><p>${subtitle} · ${item.status}</p></div>`;
    })
    .join("");

  return `<!doctype html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${blueprint.appName} Preview</title>
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <style>
    body { margin: 0; font-family: Inter, system-ui, sans-serif; background: #f4f6f8; color: #142033; }
    .shell { max-width: 430px; margin: 0 auto; min-height: 100vh; background: white; box-shadow: 0 10px 24px rgba(15,23,42,.12); }
    .hero { background: linear-gradient(135deg, #1f3a5f, #2f4f6f); color: white; padding: 28px; border-radius: 0 0 20px 20px; }
    .badge { display: inline-flex; background: rgba(255,255,255,.18); border-radius: 999px; padding: 7px 10px; font-size: 12px; font-weight: 800; margin-bottom: 14px; }
    h1 { margin: 0 0 10px; font-size: 30px; line-height: 1; }
    p { margin: 0; line-height: 1.5; }
    .content { padding: 22px; display: grid; gap: 14px; }
    .stats { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; }
    .card { border: 1px solid #d8dee8; border-radius: 14px; padding: 16px; background: #f8fafc; }
    .label { color: #64748b; font-size: 12px; font-weight: 800; }
    .value { display: block; margin-top: 6px; font-size: 24px; font-weight: 900; }
  </style>
</head>
<body>
  <main class="shell">
    <section class="hero">
      <div class="badge">${blueprint.eyebrow}</div>
      <h1>${blueprint.appName}</h1>
      <p>${blueprint.description}</p>
    </section>

    <section class="content">
      <div class="stats">
        <div class="card"><div class="label">${blueprint.statsLabels.active}</div><strong class="value">${active}</strong></div>
        <div class="card"><div class="label">${blueprint.statsLabels.value}</div><strong class="value">$${Math.round(totalValue / 1000)}k</strong></div>
        <div class="card"><div class="label">Total ${blueprint.primaryEntity}</div><strong class="value">${blueprint.samples.length}</strong></div>
        <div class="card"><div class="label">${blueprint.statsLabels.followUp}</div><strong class="value">${active}</strong></div>
      </div>

      ${sampleCards}
    </section>
  </main>
</body>
</html>`;
}

export function renderBusinessApp(blueprint: BusinessAppBlueprint): RenderedBusinessApp {
  const files: GeneratedBusinessFile[] = [
    {
      path: "package.json",
      language: "json",
      purpose: "Project dependencies and scripts.",
      content: createPackageJson(blueprint.slug),
    },
    {
      path: "next.config.mjs",
      language: "javascript",
      purpose: "Next.js configuration.",
      content: createNextConfig(),
    },
    {
      path: "next-env.d.ts",
      language: "ts",
      purpose: "Next.js type declarations.",
      content: createNextEnv(),
    },
    {
      path: "tsconfig.json",
      language: "json",
      purpose: "TypeScript configuration.",
      content: createTsconfig(),
    },
    {
      path: "app/layout.tsx",
      language: "tsx",
      purpose: "Root app layout.",
      content: createLayout(blueprint.appName),
    },
    {
      path: "app/page.tsx",
      language: "tsx",
      purpose: "Main generated business app.",
      content: createPage(blueprint),
    },
    {
      path: "app/globals.css",
      language: "css",
      purpose: "Global styles and app classes.",
      content: createGlobalsCss(),
    },
    {
      path: "README.md",
      language: "markdown",
      purpose: "Setup and run instructions.",
      content: `# ${blueprint.appName}

${blueprint.description}

## Run locally

npm install

npm run dev

Open the local URL printed in the terminal.

## Generated by Embr

This starter is intentionally local-first and uses sample data.
`,
    },
  ];

  return {
    templateId: blueprint.appType,
    appName: blueprint.appName,
    slug: blueprint.slug,
    platform: "business_tool",
    framework: "Next.js",
    summary: blueprint.description,
    previewHtml: createPreviewHtml(blueprint),
    previewType: "interactive_html",
    previewNotes:
      "This preview shows the generated business app layout. The exported project includes a runnable Next.js app.",
    files,
    nextSteps: blueprint.nextSteps,
  };
}
